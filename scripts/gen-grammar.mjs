// Generates syntaxes/easycrypt.tmLanguage.json from the `(* KW: category *)`
// annotations in EasyCrypt's lexer:
//
//   node scripts/gen-grammar.mjs path/to/easycrypt/src/ecLexer.mll

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const lexer = process.argv[2];
if (!lexer) {
  console.error("usage: node scripts/gen-grammar.mjs path/to/easycrypt/src/ecLexer.mll");
  process.exit(1);
}

const keywords = {};
for (const raw of readFileSync(lexer, "utf8").split("\n")) {
  const line = raw.replace(/\s+/g, "");
  const m = /^"(.*?)",(.*?);\(\*KW:(.*?)\*\)$/.exec(line);
  if (m) (keywords[m[3]] ??= new Set()).add(m[1]);
}
const expected = ["global", "tactic", "tactical", "bytac", "prog", "dangerous", "internal"];
for (const cat of expected) {
  if (!keywords[cat]?.size) throw new Error(`no keywords found for category "${cat}" in ${lexer}`);
}

const words = (cat) =>
  [...keywords[cat]]
    .sort((a, b) => b.length - a.length || a.localeCompare(b))
    .map((w) => w.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"))
    .join("|");
const kw = (cat, scope) => ({ name: scope, match: `\\b(?:${words(cat)})\\b` });

const IDENT = "[A-Za-z_][A-Za-z0-9_']*";

const grammar = {
  $schema: "https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json",
  name: "EasyCrypt",
  scopeName: "source.easycrypt",
  comment: `Generated by scripts/gen-grammar.mjs from ecLexer.mll. Do not edit by hand.`,
  patterns: [
    { include: "#comments" },
    { include: "#strings" },
    { include: "#declarations" },
    { include: "#keywords" },
    { include: "#literals" },
    { include: "#names" },
  ],
  repository: {
    comments: {
      patterns: [
        {
          comment: "(*op*) and ( op ) are operators, not comments",
          name: "keyword.operator.easycrypt",
          match: "\\((?=\\*[=<>+\\-*/\\\\%&^|:#$]*\\))\\*?[=<>+\\-*/\\\\%&^|:#$]*\\)",
        },
        {
          name: "comment.block.documentation.easycrypt",
          begin: "\\(\\*[&^]",
          end: "[&^]?\\*\\)",
          patterns: [{ include: "#nestedComment" }],
        },
        {
          name: "comment.block.easycrypt",
          begin: "\\(\\*",
          end: "\\*\\)",
          patterns: [{ include: "#nestedComment" }],
        },
      ],
    },
    nestedComment: {
      begin: "\\(\\*",
      end: "\\*\\)",
      patterns: [{ include: "#nestedComment" }],
    },
    strings: {
      name: "string.quoted.double.easycrypt",
      begin: '"',
      end: '"',
      patterns: [{ name: "constant.character.escape.easycrypt", match: "\\\\." }],
    },
    declarations: {
      patterns: [
        {
          match: `\\b(lemma|axiom|hint|equiv|hoare|phoare|ehoare|realize)\\s+(${IDENT})`,
          captures: {
            1: { name: "keyword.control.easycrypt" },
            2: { name: "entity.name.function.lemma.easycrypt" },
          },
        },
        {
          match: `\\b(op|pred|abbrev|const|inductive|notation)\\s+(?:\\[[^\\]]*\\]\\s*)?(${IDENT})`,
          captures: {
            1: { name: "keyword.control.easycrypt" },
            2: { name: "entity.name.function.easycrypt" },
          },
        },
        {
          match: `\\b(module\\s+type|module|type|subtype)\\s+(?:\\([^)]*\\)\\s*)?(${IDENT})`,
          captures: {
            1: { name: "keyword.control.easycrypt" },
            2: { name: "entity.name.type.easycrypt" },
          },
        },
        {
          match: `\\b(theory|section)\\s+(${IDENT})`,
          captures: {
            1: { name: "keyword.control.easycrypt" },
            2: { name: "entity.name.namespace.easycrypt" },
          },
        },
      ],
    },
    keywords: {
      patterns: [
        kw("dangerous", "invalid.illegal.admit.easycrypt"),
        kw("global", "keyword.control.easycrypt"),
        kw("bytac", "keyword.other.closing-tactic.easycrypt"),
        kw("tactical", "keyword.operator.tactical.easycrypt"),
        kw("tactic", "support.function.tactic.easycrypt"),
        kw("prog", "keyword.other.program.easycrypt"),
        kw("internal", "keyword.other.internal.easycrypt"),
      ],
    },
    literals: {
      patterns: [
        { name: "constant.numeric.easycrypt", match: "\\b(?:0x[0-9a-fA-F]+|[0-9]+(?:\\.[0-9]+)?)\\b" },
        { name: "constant.language.easycrypt", match: "\\b(?:true|false)\\b" },
      ],
    },
    names: {
      patterns: [
        { name: "variable.other.memory.easycrypt", match: `&(?:${IDENT}|[0-9]+)` },
        { name: "storage.type.variable.easycrypt", match: `'${IDENT}` },
        // `Ring.` in `Ring.addrC`, but not a name ending a sentence (`import Ring.`).
        { name: "entity.name.namespace.easycrypt", match: `\\b[A-Z][A-Za-z0-9_']*(?=\\.[A-Za-z_(])` },
      ],
    },
  },
};

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
writeFileSync(join(root, "syntaxes", "easycrypt.tmLanguage.json"), JSON.stringify(grammar, null, 2) + "\n");
const counts = expected.map((c) => `${c} ${keywords[c].size}`).join(", ");
console.log(`Wrote syntaxes/easycrypt.tmLanguage.json (${counts})`);
